"""简历文本的敏感信息（PII）脱敏。

## 为什么需要

候选人简历里必然带手机号、邮箱、身份证号，这些属于**个人敏感信息**。
在这个系统里它们有两条泄露路径：

  1. **检索证据**：每条推荐都会附上简历原文引用（``evidence[].quote``），
     这些引用会随着接口返回给前端、写进导出的报告——手机号就跟着出去了。
  2. **送进大模型**：生成推荐解释时，整段简历文本会被上传到第三方模型服务。
     简历本来就该"不出本机"，但为了解释质量又不得不调用模型，这是现实取舍。

## 设计取舍

1. **只脱敏输出，不动入库原文。**
   入库文本是切分、向量化、关键词召回的基础，改一个字都可能影响召回结果；
   而展示层打码不影响任何评分。所以脱敏只发生在"往外送"的边界上。
2. **保留可辨识的片段（前 3 后 4），不做全遮蔽。**
   招聘方经常要靠手机号后四位跟候选人核对身份，全打码反而破坏可用性。
   脱敏的目标是"不能被直接拨通/发信"，而不是"看不出这是一串号码"。
3. **姓名不打码。** 姓名是招聘流程的核心字段，打掉系统就没法用了；
   手机号和邮箱才是能直接造成骚扰和泄露的部分。
4. **正则宁可保守。** 漏掉一种罕见格式，比把简历里的业绩数字（"2024 年销售额
   1.2 亿"）误打成 ``1***`` 要好——误伤会让候选人看起来像信息损坏。
"""

from __future__ import annotations

import re

__all__ = ["mask_pii", "mask_phone", "mask_email", "mask_id_card"]

# 中国大陆手机号：1 开头，第二位 3-9，共 11 位。
# 前后用 (?<!\d) / (?!\d) 卡边界，避免把 18 位身份证的中间 11 位也匹配进来。
_PHONE = re.compile(r"(?<!\d)(1[3-9]\d)\d{4}(\d{4})(?!\d)")

# 邮箱：保留首字母和完整域名，中间的本地部分打码。
# 保留域名是因为 @company.com 本身就是有价值的招聘信号（判断是否同行/大厂）。
_EMAIL = re.compile(r"([A-Za-z0-9])([A-Za-z0-9._%+-]*)@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)")

# 二代身份证：6 位地址码 + 8 位出生日期 + 4 位顺序码（末位可能是 X）。
_ID_CARD = re.compile(r"(?<!\d)(\d{6})\d{8}(\d{3}[\dXx])(?!\d)")


def mask_phone(text: str) -> str:
    """``13800000001`` -> ``138****0001``"""
    return _PHONE.sub(r"\1****\2", text)


def mask_email(text: str) -> str:
    """``lin.demo@example.com`` -> ``l***@example.com``"""
    return _EMAIL.sub(lambda m: f"{m.group(1)}***@{m.group(3)}", text)


def mask_id_card(text: str) -> str:
    """``110101199001011234`` -> ``110101********1234``"""
    return _ID_CARD.sub(r"\1********\2", text)


def mask_pii(text: str) -> str:
    """按 身份证 -> 手机号 -> 邮箱 的顺序脱敏。

    先身份证：它是一串 18 位连续数字，先处理掉可以避免后续规则在长数字串里
    误判边界。
    """
    if not text:
        return text
    return mask_email(mask_phone(mask_id_card(text)))
